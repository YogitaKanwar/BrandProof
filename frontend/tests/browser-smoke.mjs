await new Promise((resolve, reject) => { socket.addEventListener('open', resolve); socket.addEventListener('error', reject) })
let sequence = 0
const pending = new Map()
let demoResponseId = ''
const browserErrors=[]
socket.addEventListener('message', event => {
  const data = JSON.parse(event.data)
  if(data.method==='Runtime.exceptionThrown')browserErrors.push(data.params.exceptionDetails.exception?.description||data.params.exceptionDetails.text)
  if (data.method === 'Network.responseReceived' && data.params.response.url.endsWith('/api/v1/demo-sessions')) demoResponseId = data.params.requestId
  const handler = pending.get(data.id)
  if (handler) {
    pending.delete(data.id)
    if (data.error) handler.reject(new Error(data.error.message))
    else handler.resolve(data.result)
  }
})
function send(method, params = {}) {
  return new Promise((resolve, reject) => {
    const id = ++sequence
    pending.set(id, { resolve, reject })
    socket.send(JSON.stringify({ id, method, params }))
  })
}
async function evaluate(expression) {
  const result = await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true })
  if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails))
  return result.result.value
}
async function waitFor(expression) {
  for (let attempt = 0; attempt < 100; attempt++) {
    if (await evaluate(expression)) return
    await new Promise(resolve => setTimeout(resolve, 50))
  }
  throw new Error(`Timed out: ${expression}`)
}
async function pointerClick(selector){
  const point=await evaluate(`(async()=>{const element=document.querySelector(${JSON.stringify(selector)});if(!element)throw new Error('Visible control missing');element.scrollIntoView({block:'center'});await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));const rect=element.getBoundingClientRect();const x=rect.left+rect.width/2,y=rect.top+rect.height/2;const hit=document.elementFromPoint(x,y);return {x,y,visible:rect.width>0&&rect.height>0&&(hit===element||element.contains(hit)),disabled:!!element.disabled};})()`)
  assert.equal(point.visible,true,`Control is obscured: ${selector}`);assert.equal(point.disabled,false)
  await send('Input.dispatchMouseEvent',{type:'mousePressed',x:point.x,y:point.y,button:'left',clickCount:1})
  await send('Input.dispatchMouseEvent',{type:'mouseReleased',x:point.x,y:point.y,button:'left',clickCount:1})
}
